"use client";

// Forwardable one-page market-sizing report (tournament finalist · P2.4). A clean,
// print-first rendering of an existing TAM artifact — the document a partner pastes
// into a memo or forwards to a fund. Everything here is derived from the TAMOutput
// the user already has; no new number is computed. "Print / Save as PDF" uses the
// browser's native print to PDF, scoped by the .tam-report print stylesheet below.

import { useQuery } from "@tanstack/react-query";
import Link from "next/link";

import { ConvergenceBanner } from "@/components/charts/ConvergenceBanner";
import { TornadoChart } from "@/components/charts/TornadoChart";
import { Button } from "@/components/ui/Button";
import { formatCompact, lensLabel, tierLabel } from "@/lib/format";
import { sensitivityQuery } from "@/lib/queries";
import type { InputUsed, Scenario, TAMOutput } from "@/lib/schemas";
import { isDegenerate, midScenario, tamRange } from "@/lib/tam";

const MULTIPLICATIVE_LENSES = new Set([
  "cost_efficiency",
  "revenue_generation",
  "latent_demand",
  "platform_throughput",
  "productivity_uplift",
]);

export function TamReport({ tam }: { tam: TAMOutput }) {
  const concept = tam.target.concept_name ?? tam.target.concept.replace(/-/g, " ");
  const range = tamRange(tam);
  const unit = midScenario(tam).unit;
  const generated = tam.created_at.slice(0, 10);

  return (
    <main className="tam-report mx-auto w-full max-w-[860px] px-8 py-10">
      <ReportPrintStyles />

      {/* Screen-only action bar (hidden in print). */}
      <div data-print-hide className="mb-8 flex flex-wrap items-center justify-between gap-3">
        <Link
          href={`/tam/${tam.state_hash}`}
          className="text-[13px] text-[var(--fg-3)] transition-colors hover:text-[var(--fg-1)]"
        >
          ← Back to interactive TAM
        </Link>
        <Button sm onClick={() => window.print()}>
          Print / Save as PDF
        </Button>
      </div>

      {/* Letterhead. */}
      <header className="border-b-2 border-[var(--fg-1)] pb-5">
        <div className="flex items-center justify-between">
          <span className="font-mono text-[11px] uppercase tracking-[0.18em] text-[var(--fg-3)]">
            Strata · Market Sizing Report
          </span>
          <span className="font-mono text-[11px] text-[var(--fg-3)]">{generated}</span>
        </div>
        <h1 className="display mt-3 text-[34px] leading-[1.1] text-[var(--fg-1)]">{concept}</h1>
        <p className="mt-2 text-[13px] text-[var(--fg-3)]">
          Total addressable market · USD nominal · {tam.method_families_used.length} independent
          method
          {tam.method_families_used.length === 1 ? "" : "s"} · permalink{" "}
          <span className="font-mono text-[var(--fg-2)]">{tam.state_hash.slice(0, 12)}</span>
        </p>
      </header>

      {/* Executive KPI strip. */}
      <section className="report-block mt-7 grid grid-cols-2 gap-4 sm:grid-cols-4">
        <Kpi label="Triangulated TAM" value={formatCompact(range.mid, unit)} emphasis />
        <Kpi
          label="Range"
          value={
            isDegenerate(tam)
              ? "single point"
              : `${formatCompact(range.low, unit)} – ${formatCompact(range.high, unit)}`
          }
        />
        <Kpi label="Methods" value={String(tam.method_families_used.length)} />
        <Kpi label="Independence" value={tam.independence_score.toFixed(2)} />
      </section>

      {/* Convergence cross-check (only when triangulated). */}
      {tam.convergence ? (
        <section className="report-block mt-7">
          <SectionTitle>The cross-check</SectionTitle>
          <div className="mt-3">
            <ConvergenceBanner convergence={tam.convergence} />
          </div>
        </section>
      ) : null}

      {/* How it was sized — the math, per method. */}
      <section className="report-block mt-7">
        <SectionTitle>How it was sized</SectionTitle>
        <div className="mt-3 flex flex-col gap-4">
          {tam.scenarios.map((s) => (
            <MethodCard key={`${s.framework}-${s.framework_variant ?? ""}`} scenario={s} />
          ))}
        </div>
      </section>

      {/* Sensitivity — which assumption moves the answer most. */}
      <SensitivityBlock slug={tam.target.concept} />

      {/* Provenance — every sourced input behind the number. */}
      <ProvenanceTable tam={tam} />

      {/* Honesty footnotes. */}
      <FootnotesBlock tam={tam} />

      <footer className="mt-10 border-t border-[var(--border-1)] pt-4 text-[11px] text-[var(--fg-3)]">
        Generated by Strata on {generated}. Every figure traces to a cited source snapshot (SHA-256
        pinned). Reproducible at /tam/{tam.state_hash.slice(0, 12)}. This is a sizing estimate, not
        investment advice.
      </footer>
    </main>
  );
}

function Kpi({ label, value, emphasis }: { label: string; value: string; emphasis?: boolean }) {
  return (
    <div className="canvas-card p-4">
      <div className="text-[10px] uppercase tracking-[0.06em] text-[var(--fg-3)]">{label}</div>
      <div
        className={`mt-1 tabular-nums text-[var(--fg-1)] ${
          emphasis ? "display text-[26px] leading-none" : "text-[18px] font-medium"
        }`}
      >
        {value}
      </div>
    </div>
  );
}

function SectionTitle({ children }: { children: string }) {
  return (
    <h2 className="font-mono text-[11px] uppercase tracking-[0.14em] text-[var(--fg-2)]">
      {children}
    </h2>
  );
}

function MethodCard({ scenario: s }: { scenario: Scenario }) {
  const multiplicative = MULTIPLICATIVE_LENSES.has(s.lens) && s.inputs_used.length > 1;
  return (
    <div className="canvas-card p-5">
      <div className="flex items-baseline justify-between gap-3">
        <div className="text-[14px] font-medium text-[var(--fg-1)]">
          {s.framework.replace(/-/g, " ")}
        </div>
        <div className="tabular-nums text-[16px] font-medium text-[var(--fg-1)]">
          {formatCompact(s.value, s.unit)}
        </div>
      </div>
      <div className="mt-0.5 font-mono text-[10px] uppercase tracking-wide text-[var(--fg-3)]">
        {lensLabel(s.lens)}
      </div>

      {multiplicative ? (
        <div className="mt-3 flex flex-wrap items-center gap-x-1.5 gap-y-1 text-[12px] text-[var(--fg-2)]">
          {s.inputs_used.map((iu, i) => (
            <span key={iu.primitive_slug} className="inline-flex items-center gap-1.5">
              {i > 0 ? <span className="text-[var(--fg-4)]">×</span> : null}
              <span className="tabular-nums">
                {iu.value != null ? formatCompact(iu.value, iu.unit) : iu.role_name}
              </span>
            </span>
          ))}
          <span className="text-[var(--fg-4)]">=</span>
          <span className="font-medium tabular-nums text-[var(--fg-1)]">
            {formatCompact(s.value, s.unit)}
          </span>
        </div>
      ) : (
        <ul className="mt-3 flex flex-col gap-1 text-[12px] text-[var(--fg-2)]">
          {s.inputs_used.map((iu) => (
            <li key={iu.primitive_slug} className="flex items-center justify-between gap-3">
              <span>{iu.name ?? iu.role_name}</span>
              <span className="tabular-nums text-[var(--fg-3)]">
                {iu.value != null ? formatCompact(iu.value, iu.unit) : "—"}
              </span>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

function SensitivityBlock({ slug }: { slug: string }) {
  const q = useQuery(sensitivityQuery(slug));
  if (!q.data || q.data.inputs.length === 0) return null;
  return (
    <section className="report-block mt-7">
      <SectionTitle>What moves the answer</SectionTitle>
      <p className="mt-1 text-[12px] text-[var(--fg-3)]">
        Each assumption swung ±{Math.round(q.data.pct * 100)}% — the longest bar is the number to
        defend first.
      </p>
      <div className="mt-3">
        <TornadoChart data={q.data} />
      </div>
    </section>
  );
}

function ProvenanceTable({ tam }: { tam: TAMOutput }) {
  // Dedupe inputs across scenarios by primitive slug — one row per sourced number.
  const seen = new Map<string, InputUsed>();
  for (const s of tam.scenarios) {
    for (const iu of s.inputs_used) {
      if (!seen.has(iu.primitive_slug)) seen.set(iu.primitive_slug, iu);
    }
  }
  const rows = [...seen.values()];
  if (rows.length === 0) return null;

  return (
    <section className="report-block mt-7">
      <SectionTitle>Sources &amp; provenance</SectionTitle>
      <div className="mt-3 overflow-hidden rounded-[var(--r-3)] border border-[var(--border-1)]">
        <table className="w-full text-left text-[12px]">
          <thead>
            <tr className="border-b border-[var(--border-1)] text-[10px] uppercase tracking-wide text-[var(--fg-3)]">
              <th className="px-3 py-2 font-medium">Input</th>
              <th className="px-3 py-2 font-medium">Value</th>
              <th className="px-3 py-2 font-medium">Tier</th>
              <th className="px-3 py-2 font-medium">Snapshot</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((iu) => (
              <tr
                key={iu.primitive_slug}
                className="border-b border-[var(--border-1)] last:border-0"
              >
                <td className="px-3 py-2 text-[var(--fg-1)]">{iu.name ?? iu.primitive_slug}</td>
                <td className="px-3 py-2 tabular-nums text-[var(--fg-2)]">
                  {iu.value != null ? formatCompact(iu.value, iu.unit) : "—"}
                </td>
                <td className="px-3 py-2 text-[var(--fg-2)]">
                  {iu.source_tier ? tierLabel(iu.source_tier) : "composite"}
                </td>
                <td className="px-3 py-2 font-mono text-[10px] text-[var(--fg-3)]">
                  {iu.snapshot_sha256 ? iu.snapshot_sha256.slice(0, 10) : "—"}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

function FootnotesBlock({ tam }: { tam: TAMOutput }) {
  const notes = new Map<string, string>();
  for (const s of tam.scenarios) {
    for (const b of s.banners) notes.set(b.kind, b.message);
  }
  if (tam.uses_synthetic_primitives) {
    notes.set(
      "synthetic",
      "Contains a what-if / modeled input — not a fully externally-sourced figure.",
    );
  }
  if (notes.size === 0) return null;
  return (
    <section className="report-block mt-7">
      <SectionTitle>Footnotes</SectionTitle>
      <ul className="mt-2 flex flex-col gap-1.5 text-[11px] text-[var(--fg-3)]">
        {[...notes.entries()].map(([kind, message]) => (
          <li key={kind}>
            <span className="font-mono uppercase text-[var(--warning)]">{kind}</span> — {message}
          </li>
        ))}
      </ul>
    </section>
  );
}

// Print stylesheet, scoped to this report. Drops interactive chrome, tightens
// margins, and keeps each block from splitting across a page break.
function ReportPrintStyles() {
  return (
    <style>{`
      @media print {
        .tam-report [data-print-hide] { display: none !important; }
        .tam-report { max-width: none; padding: 0; }
        .tam-report .report-block { break-inside: avoid; page-break-inside: avoid; }
        .tam-report .canvas-card { box-shadow: none !important; border: 1px solid #ddd; }
      }
    `}</style>
  );
}
