"""Acceptance tests for the corrected TAM-77 v2 pipeline (PR #44).

Verifies the 12 methodology corrections in
``docs/superpowers/specs/2026-05-26-tam-77-corrected-methodology.md`` by
loading the YAML data bank, running ``size_concept(slug)`` on each portfolio
concept generated by ``scripts/tam_77_pipeline.py`` (or the 3 hand-crafted
worked examples), and asserting:

  - Yotta lands India-only with the expected $3-5B band.
  - MetaVoice (voice-ai-infra-global) lands at the spec body's $13-16B band.
  - Piramidal carries the multi-jurisdiction paraphrase (FDA/CE/CDSCO/ANVISA).
  - Every concept resolves through the evaluator DAG (no orphans).
  - Every concept's chosen framework lens matches the concept's declared lens.
  - Primitives bound to us_only_regulated companies carry geo=["US"].

These tests are read-only against the data bank; they do not call any external
APIs. They will be skipped if the data bank does not contain the corresponding
concept (e.g. running before the pipeline has emitted YAML).
"""

